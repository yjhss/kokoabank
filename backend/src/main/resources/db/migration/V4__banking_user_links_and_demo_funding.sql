-- V4: Connect Kakao platform users to legacy banking users.
-- Add an audit trail for local-only simulated funding.

CREATE TABLE banking_user_links (
    platform_user_id BIGINT PRIMARY KEY,
    banking_user_id BIGINT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_banking_links_platform_user
        FOREIGN KEY (platform_user_id)
        REFERENCES platform_users(id),

    CONSTRAINT fk_banking_links_banking_user
        FOREIGN KEY (banking_user_id)
        REFERENCES users(id)
);

CREATE TABLE banking_demo_funding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    amount BIGINT NOT NULL,
    balance_after BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_demo_funding_account
        FOREIGN KEY (account_id)
        REFERENCES accounts(id),

    CONSTRAINT chk_demo_funding_amount
        CHECK (amount > 0),

    CONSTRAINT chk_demo_funding_balance
        CHECK (balance_after >= 0)
);

CREATE INDEX idx_demo_funding_account_created
    ON banking_demo_funding(account_id, created_at DESC);
