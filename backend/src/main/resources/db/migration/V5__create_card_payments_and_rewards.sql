-- V5: Simulated card payments and cashback rewards.
-- All amounts are integer KRW. No real funds are transferred.

CREATE TABLE reward_draws (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_user_id BIGINT NOT NULL,
    cashback_rate INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at TIMESTAMPTZ,

    CONSTRAINT fk_reward_draw_user
        FOREIGN KEY (platform_user_id)
        REFERENCES platform_users(id),

    CONSTRAINT chk_reward_cashback_rate
        CHECK (cashback_rate IN (1, 2, 3, 5)),

    CONSTRAINT chk_reward_draw_status
        CHECK (status IN ('AVAILABLE', 'USED')),

    CONSTRAINT chk_reward_draw_usage
        CHECK (
            (status = 'AVAILABLE' AND used_at IS NULL)
            OR
            (status = 'USED' AND used_at IS NOT NULL)
        )
);

CREATE UNIQUE INDEX uq_reward_draw_available_user
    ON reward_draws(platform_user_id)
    WHERE status = 'AVAILABLE';

CREATE INDEX idx_reward_draw_user_created
    ON reward_draws(platform_user_id, created_at DESC);

CREATE TABLE card_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    reward_draw_id BIGINT NOT NULL UNIQUE,
    merchant_name VARCHAR(100) NOT NULL,
    amount BIGINT NOT NULL,
    cashback_rate INTEGER NOT NULL,
    cashback_amount BIGINT NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_card_payment_account
        FOREIGN KEY (account_id)
        REFERENCES accounts(id),

    CONSTRAINT fk_card_payment_reward
        FOREIGN KEY (reward_draw_id)
        REFERENCES reward_draws(id),

    CONSTRAINT chk_card_payment_amount
        CHECK (amount BETWEEN 1000 AND 100000),

    CONSTRAINT chk_card_payment_rate
        CHECK (cashback_rate IN (1, 2, 3, 5)),

    CONSTRAINT chk_card_payment_cashback
        CHECK (
            cashback_amount >= 0
            AND cashback_amount <= 1000
        ),

    CONSTRAINT chk_card_payment_status
        CHECK (status = 'COMPLETED')
);

CREATE INDEX idx_card_payments_account_created
    ON card_payments(account_id, created_at DESC);

CREATE TABLE card_payment_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    entry_type VARCHAR(20) NOT NULL,
    amount BIGINT NOT NULL,
    balance_after BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_card_ledger_payment
        FOREIGN KEY (payment_id)
        REFERENCES card_payments(id),

    CONSTRAINT fk_card_ledger_account
        FOREIGN KEY (account_id)
        REFERENCES accounts(id),

    CONSTRAINT uq_card_ledger_entry
        UNIQUE (payment_id, entry_type),

    CONSTRAINT chk_card_ledger_type
        CHECK (entry_type IN ('PAYMENT', 'CASHBACK')),

    CONSTRAINT chk_card_ledger_amount
        CHECK (amount > 0),

    CONSTRAINT chk_card_ledger_balance
        CHECK (balance_after >= 0)
);

CREATE INDEX idx_card_ledger_account_created
    ON card_payment_ledger(account_id, created_at DESC);
